/**
 * Factory synths (D80): patches in the style of well-known songs and synths. Ids are stable:
 * projects store them (the first ten were the original presets).
 */
import { upgradeV1, type SynthPatch } from "../model/synth";
// written as version 1 patches, upgraded (until they're voiced again for version 2, plan §0.6e H)
import { makePatch, type PatchSpec } from "../model/synthV1";

export type SynthGroup = "Bass" | "Leads" | "Pads" | "Keys" | "Plucks & stabs" | "FX";

export interface FactorySynth {
  id: string;
  name: string;
  group: SynthGroup;
  /** What it's in the style of. */
  note?: string;
  patch: SynthPatch;
}

const synth = (
  id: string,
  name: string,
  group: SynthGroup,
  spec: PatchSpec,
  note?: string,
): FactorySynth => ({ id, name, group, note, patch: upgradeV1(makePatch(spec)) });

